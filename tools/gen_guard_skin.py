"""Embed the supplied PNGs as Rust bytes for the source-only native bundle."""

import argparse
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets" / "minecraft" / "textures" / "entity" / "guard_villagers"
OUTPUT = ROOT / "mixins" / "guard_villagers" / "skins.rs"
NAMES = ("guard-villager", "guard-villager-i", "villager-guard-ii", "villager-archer")


def source():
    lines = ["// Generated by tools/gen_guard_skin.py; the PNG bytes are unchanged.",
             "#[rustfmt::skip]", "pub const SKINS: [(&str, &[u8]); 4] = ["]
    for name in NAMES:
        data = (ASSETS / f"{name}.png").read_bytes()
        if data[:8] != b"\x89PNG\r\n\x1a\n" or struct.unpack(">II", data[16:24]) != (64, 64):
            raise ValueError(f"{name} must be a 64x64 PNG")
        lines.append(f'    ("guard_villagers:entity/{name}", &[')
        for offset in range(0, len(data), 24):
            lines.append("        " + ", ".join(str(b) for b in data[offset:offset + 24]) + ",")
        lines.append("    ]),")
    lines.append("];")
    lines.append('''

pub fn append(images: &mut Vec<(String, u32, u32, Vec<u8>)>) {
    for (name, png) in SKINS {
        let (w, h, pixels) = crate::hud::decode_bytes(png).expect("valid embedded guard skin");
        images.push((name.into(), w, h, pixels));
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn all_skins_decode_without_external_files() {
        let mut images = vec![("existing".into(), 1, 1, vec![255; 4])];
        super::append(&mut images);
        assert_eq!(images.len(), 5);
        assert_eq!(images[0].0, "existing");
        for (name, w, h, pixels) in &images[1..] {
            assert!(name.starts_with("guard_villagers:entity/"));
            assert_eq!((*w, *h), (64, 64));
            assert_eq!(pixels.len(), 64 * 64 * 4);
            assert!(pixels.chunks_exact(4).any(|p| p[3] == 0));
            assert!(pixels.chunks_exact(4).any(|p| p[3] == 255));
        }
        let names: std::collections::HashSet<_> = images.iter().map(|i| &i.0).collect();
        assert_eq!(names.len(), images.len());
    }
}
''')
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = source()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("skins.rs is stale; run tools/gen_guard_skin.py")
        print("Embedded PNG bytes match the source assets")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
        print(f"Wrote {OUTPUT}")
